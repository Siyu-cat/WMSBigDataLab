export type LineHighlight = { text: string; color: string };

export type ScriptLine =
  | { type: 'scene'; text: string; sub?: string }
  | { type: 'narration'; text: string; highlight?: LineHighlight | LineHighlight[] }
  | { type: 'cg'; name: string; label?: string; inst?: number }
  | { type: 'getclue'; text: string; color?: string }
  | { type: 'dialogue'; speaker: string; text: string; highlight?: LineHighlight | LineHighlight[] }
  | { type: 'inner'; speaker: string; text: string; highlight?: LineHighlight | LineHighlight[] }
  | { type: 'interact'; text: string; indent?: number }
  | { type: 'gap' }
  | {
      type: 'expand';
      label: string;
      lines: ScriptLine[];
      id?: string;
      when?: string[];
      keyInfo?: string[];
      gate?: { require: string[]; lockedLines: ScriptLine[]; disabled?: boolean };
    }
  | { type: 'choice'; options: ChoiceOption[]; key?: string; linked?: string; defer?: boolean }
  | {
      type: 'think';
      id: string;
      correct: string[];
      pool?: string[];
      disabled?: string[];
      correctLines: ScriptLine[];
      wrongLines: ScriptLine[];
    }
  | {
      type: 'evidencePick';
      id: string;
      correct: string;
      correctLines: ScriptLine[];
      wrongLines: ScriptLine[];
      debate?: {
        ledgerLabel: string;
        ledgerLines: ScriptLine[];
        printLabel: string;
        printLines: ScriptLine[];
      };
    };

